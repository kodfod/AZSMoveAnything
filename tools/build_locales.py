"""Generate game-readable Lua from UTF-8 JSON; no third-party Python dependency.
Run from the repository root: python tools/build_locales.py [--check]
"""
from pathlib import Path
import argparse, json, re

ROOT = Path(__file__).resolve().parents[1]
LANGUAGES = ['en', 'pl', 'cs', 'de', 'pt', 'es', 'fr', 'ro', 'tr', 'ru', 'uk', 'zh', 'ja', 'ko']
FORMAT = re.compile(r'%(?:[-+ #0]*\d*(?:\.\d+)?)[cdeEfgGiouXxqs]')

def signature(text):
    text = text.replace('%%', '')
    if '%' in FORMAT.sub('', text):
        raise ValueError(f'Invalid format token in {text!r}')
    return FORMAT.findall(text)

def generated_files():
    catalogs = {code: json.loads((ROOT/'locales'/f'{code}.json').read_text(encoding='utf-8')) for code in LANGUAGES}
    english = catalogs['en']
    for code, entries in catalogs.items():
        if set(entries) != set(english):
            raise ValueError(f'{code}: keys differ from en.json')
        for key, value in entries.items():
            if not isinstance(value, str) or not value.strip():
                raise ValueError(f'{code}: empty translation for {key!r}')
            if signature(value) != signature(english[key]):
                raise ValueError(f'{code}: changed format placeholders in {key!r}')
    literal = lambda value: json.dumps(value, ensure_ascii=False)
    def table(entries):
        return '\n'.join('\t['+literal(key)+'] = '+literal(value)+',' for key, value in entries.items())
    english_lua = 'MoveAnything_Strings = {\n'+table(english)+'\n};\n'
    lines = ['-- Generated by tools/build_locales.py. Edit locales/*.json instead.', 'MoveAnything_Locales = {};']
    for code in LANGUAGES:
        if code != 'en':
            lines += ['MoveAnything_Locales.'+code+' = {', table(catalogs[code]), '};']
    probes = json.loads((ROOT/'locales/probes.json').read_text(encoding='utf-8'))
    lines += ['-- Native class/spell names: read-only language detection, no gameplay writes.', 'MoveAnything_LanguageProbes = {};']
    for code in LANGUAGES:
        lines += ['MoveAnything_LanguageProbes.'+code+' = {', table(probes[code]), '};']
    return {'MoveAnything/Strings.lua': english_lua, 'MoveAnything/Locales.lua': '\n'.join(lines)+'\n'}

def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true', help='Fail if committed Lua needs regenerating; write nothing.')
    args = parser.parse_args()
    for name, text in generated_files().items():
        target = ROOT/name
        if args.check:
            if not target.exists() or target.read_text(encoding='utf-8') != text:
                raise SystemExit(f'{name} is stale. Run python tools/build_locales.py')
        else:
            target.write_text(text, encoding='utf-8')
    print('PASS: complete catalogs for 14 languages; format placeholders preserved; generated Lua is current')

if __name__ == '__main__':
    main()
